# answers to questions on `Week-01-GitHub-Workflow-Exercise.pdf`

#Part 3 answers

#A. My file is saved in RStudio, but it does not appear on GitHub.
The file still needs to be staged, committed, and pushed. Saving only updates the local file.
(The file was saved locally but was not staged, committed, and pushed.)

#B. I made a commit, but GitHub still shows the older version of the file.
The commit has not been pushed. Click Push, then refresh GitHub.
(The commit was created locally but was not pushed to GitHub.)

# C. I opened RStudio and cannot find the Week 1 exercise.
The wrong project is probably open. Open tutorials-exercises.Rproj, then look in `week-01/exercises/`.
Do not clone the repository again.
(The wrong RStudio Project may be open, or the exercise was not copied into tutorials-exercises/week-01/exercises/.)

#D. I pulled course-hub, but the instructor’s new file is not visible.
Confirm that:

the course-hub project is open;
the pull finished without an error; and
you are looking in the correct Week 1 folder.
(Confirm that course-hub is the active project, the pull completed successfully, and the correct Week 1 folder is being viewed.)